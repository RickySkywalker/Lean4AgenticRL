"""Write the harbor job for a TB-2.1 run with the PSWF Terminus-2 harness.

    python -m tb21_eval.make_job --model M --work-dir W --run-dir R [--n-attempts 5] [--n-concurrent 40]
    harbor run -c R/job.json --env-file R/harbor.env

Writes, into the run directory R:
  job.json      harbor JobConfig: the PSWF agent (terminus2_dynwf.dynamic_agent:Terminus2Dynamic) with the exact
                protocol kwargs, all 89 TB-2.1 tasks (20,000 s agent budget) x n_attempts,
                n_concurrent_trials containers of 4 CPUs / 40 GB, and the network-policy instruction suffix
  overlay.yaml  docker-compose overlay attaching every task container to the guarded network (tb21_eval.netguard):
                HTTP(S) proxy + DNS on the gateway, NET_RAW dropped, no-new-privileges, Tor entry points masked,
                apt policy pins
  harbor.env    environment for the harbor process (the served tokenizer for context accounting, telemetry off)
Trials go to R/jobs/<job-name>/. Use --tasks/--job-name to write a recovery job for tasks the scorer reports as
PENDING (infrastructure failures), e.g. `--tasks compile-compcert --job-name <name>_r01`.

Choose work and run directories outside the source checkout. Trial outputs include
agent telemetry, fill profiles and trusted plan dumps.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

import tb21_eval as T


def die(msg: str) -> None:
    raise SystemExit(f"[make_job] FATAL: {msg}")


def warn(msg: str) -> None:
    print(f"[make_job] WARNING: {msg}", file=sys.stderr)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def overlay_yaml(apt_dir: Path) -> str:
    """Compose overlay for the guarded task network and package policy."""
    gw, proxy = T.GUARD_GATEWAY, f"http://{T.GUARD_GATEWAY}:{T.EGRESS_PROXY_PORT}"
    no_proxy = f"localhost,127.0.0.1,::1,{gw}"
    lines = [
        "# generated by tb21_eval.make_job; do not hand-edit",
        "# The external network is created (and verified --internal) by `python -m tb21_eval.netguard up`.",
        "services:",
        "  main:",
        "    networks:",
        "      - pswf_guarded",
        "    dns:",
        f'      - "{gw}"',
        "    environment:",
        f'      HTTP_PROXY: "{proxy}"',
        f'      HTTPS_PROXY: "{proxy}"',
        f'      http_proxy: "{proxy}"',
        f'      https_proxy: "{proxy}"',
        f'      NO_PROXY: "{no_proxy}"',
        f'      no_proxy: "{no_proxy}"',
        '      ALL_PROXY: ""',
        '      all_proxy: ""',
        "    cap_drop:",
        "      - NET_RAW",
        "    security_opt:",
        "      - no-new-privileges:true",
        "    volumes:",
    ]
    mounts = [("/dev/null", target) for target in T.TOR_MASKS]
    mounts += [(str(apt_dir / name), target) for name, target in T.APT_POLICY_MOUNTS]
    for source, target in mounts:
        src = source if source == "/dev/null" else f'"{source}"'
        lines += [
            "      - type: bind",
            f"        source: {src}",
            f'        target: "{target}"',
            "        read_only: true",
            "        bind:",
            "          create_host_path: false",
        ]
    lines += ["networks:", "  pswf_guarded:", "    external: true", f'    name: "{T.GUARD_NETWORK}"', ""]
    return "\n".join(lines)


def write_if_changed(path: Path, text: str) -> None:
    """Atomically replace `path` with `text`, and leave it untouched when it already holds exactly that text (the
    overlay and env file are shared by every job of a run dir, possibly while one of them is running)."""
    if path.is_file() and path.read_text() == text:
        return
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text)
    tmp.replace(path)


def check_inputs(args: argparse.Namespace) -> Path:
    tasks_dir = args.work_dir / "tasks-aa"
    manifest = args.work_dir / "task-manifest.json"
    if not manifest.is_file() or not tasks_dir.is_dir():
        die(f"{tasks_dir} is missing: run `python -m tb21_eval.prepare --work-dir {args.work_dir}` first")
    if not (args.work_dir / "prepare.json").is_file():
        die(f"{args.work_dir}/prepare.json is missing: `python -m tb21_eval.prepare --work-dir {args.work_dir}` has "
            "not completed (task images unverified)")
    m = json.loads(manifest.read_text())
    if m.get("derived_tree_sha256") != T.TASKS_AA_TREE_SHA256 or m.get("actual_commit") != T.TB21_REV:
        die(f"{manifest} does not describe the pinned TB-2.1 task tree ({T.TASKS_AA_TREE_SHA256})")
    for path, key in [(T.ASSETS / "network_policy.md", "network_policy.md")] + \
                     [(T.ASSETS / "apt" / n, n) for n, _ in T.APT_POLICY_MOUNTS]:
        if sha256(path) != T.EXPECTED_SHA256[key]:
            die(f"{path} was modified (it must match the packaged asset digest)")
    tok = args.model / "tokenizer.json"
    if not tok.is_file():
        die(f"{tok} not found: --model must be the LAR-27B checkpoint directory")
    if sha256(tok) != T.EXPECTED_SHA256["tokenizer.json"]:
        warn("tokenizer.json differs from the supported LAR-27B checkpoint")
    net = subprocess.run(["docker", "network", "inspect", T.GUARD_NETWORK], capture_output=True, text=True)
    if net.returncode != 0 or not json.loads(net.stdout)[0].get("Internal"):
        warn(f"guarded network {T.GUARD_NETWORK} is not up yet (sudo $(which python) -m tb21_eval.netguard up ...)")
    return tasks_dir


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", type=Path, required=True, help="LAR-27B checkpoint directory (for its tokenizer.json)")
    ap.add_argument("--work-dir", type=Path, required=True, help="kit work directory prepared by tb21_eval.prepare")
    ap.add_argument("--run-dir", type=Path, required=True, help="where job.json/overlay.yaml/harbor.env and trials go")
    ap.add_argument("--job-name", default=None, help="harbor job name (default: pswf-tb21-x<n_attempts>)")
    ap.add_argument("--n-attempts", type=int, default=T.N_ATTEMPTS, help="attempts per task (default: %(default)s)")
    ap.add_argument("--n-concurrent", type=int, default=T.N_CONCURRENT_TRIALS,
                    help="concurrent task containers (default: %(default)s)")
    ap.add_argument("--tasks", default=None, help="comma-separated subset of task names (default: all 89)")
    ap.add_argument("--api-base", default=f"http://{T.HOST}:{T.MODEL_GUARD_PORT}/v1",
                    help="OpenAI-compatible endpoint the agent calls (default: the model guard, %(default)s)")
    args = ap.parse_args()
    args.model, args.work_dir, args.run_dir = args.model.resolve(), args.work_dir.resolve(), args.run_dir.resolve()

    tasks_dir = check_inputs(args)
    names = T.TASK_NAMES if args.tasks is None else [t.strip() for t in args.tasks.split(",") if t.strip()]
    unknown = sorted(set(names) - set(T.TASK_NAMES))
    if unknown:
        die(f"unknown task(s): {unknown}")
    job_name = args.job_name or f"pswf-tb21-x{args.n_attempts}"
    jobs_dir = args.run_dir / "jobs"
    if (jobs_dir / job_name).exists():
        die(f"{jobs_dir / job_name} already exists: pick a new --job-name (to continue an interrupted run use "
            f"`harbor job resume --job-path {jobs_dir / job_name}`)")
    args.run_dir.mkdir(parents=True, exist_ok=True)
    trusted_root = args.run_dir / "dynwf_trusted" / job_name     # host-side copies of the agent's plan artifacts,
    trusted_root.mkdir(parents=True, exist_ok=True)              # deliberately outside the (agent-writable) trials

    overlay = args.run_dir / "overlay.yaml"                       # identical for every job of a run
    write_if_changed(overlay, overlay_yaml(T.ASSETS / "apt"))
    job = {
        "agents": [{
            "env": {},
            "import_path": T.AGENT_IMPORT_PATH,
            "kwargs": T.agent_kwargs(api_base=args.api_base, trusted_root=str(trusted_root)),
            "model_name": f"openai/{T.SERVED_MODEL}",
        }],
        "datasets": [{"path": str(tasks_dir), "task_names": sorted(names)}],
        "environment": {
            "cpu_enforcement_policy": "limit",
            "delete": True,
            "extra_docker_compose": [str(overlay)],
            "memory_enforcement_policy": "limit",
            "override_cpus": T.CPUS_PER_TRIAL,
            "override_memory_mb": T.MEMORY_MB_PER_TRIAL,
            "type": "docker",
        },
        "extra_instruction_paths": [str(T.ASSETS / "network_policy.md")],
        "job_name": job_name,
        "jobs_dir": str(jobs_dir),
        "n_attempts": args.n_attempts,
        "n_concurrent_trials": args.n_concurrent,
        "quiet": True,
        "retry": T.TRIAL_RETRY,
    }
    # The full run is R/job.json; a subset (recovery) job gets its own file next to it.
    job_path = args.run_dir / ("job.json" if args.tasks is None else f"job.{job_name}.json")
    job_path.write_text(json.dumps(job, indent=2, sort_keys=True) + "\n")

    env_path = args.run_dir / "harbor.env"
    write_if_changed(env_path, "\n".join([
        "# environment of the harbor process (loaded with `harbor run --env-file`)",
        "OPENAI_API_KEY=local",
        # the patched Terminus-2 counts context with the served model's own tokenizer (required by the PSWF agent)
        f"Q38_TOKENIZER_JSON={args.model / 'tokenizer.json'}",
        "Q38_SUMMARIZER_FIT=1",
        "Q38_SUMMARIZER_FIT_MARGIN_TOKENS=2048",
        "NO_PROXY=127.0.0.1,localhost",
        "no_proxy=127.0.0.1,localhost",
        "HARBOR_TELEMETRY=0",
        # keep the (inert) pre-container hook of the docker patch off even if these leak in from another kit
        "Q38_RUN_CONFIG=",
        "Q38_PRECONTAINER_HOOK=",
        "",
    ]))
    n_trials = len(names) * args.n_attempts
    print(f"[make_job] {len(names)} tasks x {args.n_attempts} attempts = {n_trials} trials, "
          f"{args.n_concurrent} concurrent; agent -> {args.api_base}")
    print(f"[make_job] wrote {job_path}, {overlay}, {env_path}")
    print(f"harbor run -c {job_path} --env-file {env_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
